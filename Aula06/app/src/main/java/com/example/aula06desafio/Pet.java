package com.example.aula06desafio;

public class Pet {
    public String nome;
    public String cor;
    public String raca;
    public int idade;
    public String aniversario;

    public Pet(String nomePet, String corPet, String racaPet, int idadePet, String aniversarioPet){
        this.nome = nomePet;
        this.cor = corPet;
        this.raca = racaPet;
        this.idade = idadePet;
        this.aniversario = aniversarioPet;
    }
}
